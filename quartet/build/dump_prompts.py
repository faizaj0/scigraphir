#!/usr/bin/env python3
"""Emit the Stage 3 prompts as a LaTeX appendix, straight from the source.

The prompts change. Retyping them into the thesis guarantees that at some point
the appendix describes a system that was never run, and nothing would catch it.
This reads the live modules instead, so regenerating is the only edit needed.

Two blocks are spliced into several prompts rather than repeated:

    PAPER_BLOCK   the paper text and its reference list, the shared cache prefix
    DELTA_SPEC    the delta contract, identical in FIND_INSPIRATIONS and REBUILD

Each is printed once and referenced from the prompts that carry it, which is
also the honest picture: they really are one string, and that is what makes the
two decompositions comparable and the paper tokens cacheable.

    python build/dump_prompts.py --out ../figures/appendix_prompts.tex
"""
from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def clean(text: str, strip: list[tuple[str, str]] | None = None) -> str:
    """Undo the .format() brace doubling, and cut out the spliced blocks.

    The model never sees `{{`; that is Python escaping. Printing it would put a
    detail of our implementation into the thesis and misrepresent the prompt.
    """
    for block, note in (strip or []):
        text = text.replace(block, f"\n[[ {note} ]]\n")
    return text.replace("{{", "{").replace("}}", "}").strip("\n")


TEMPLATE = r"""% Generated by build/dump_prompts.py -- do not edit by hand, regenerate.
%
% Requires, in the main preamble:
%   \usepackage{listings}
%   \usepackage[T1]{fontenc}
%   \lstset{basicstyle=\ttfamily\footnotesize, breaklines=true,
%           breakindent=0pt, columns=fullflexible, frame=single,
%           framesep=4pt, rulecolor=\color{black!25}, xleftmargin=0pt,
%           aboveskip=6pt, belowskip=6pt, showstringspaces=false}
%   \usepackage{xcolor}

\chapter{Stage 3 prompts}
\label{app:prompts}

Every prompt used by the decomposition pipeline of
Chapter~\ref{ch:quartet}, reproduced verbatim from the implementation.
Names in braces, such as \texttt{\{text\}} and \texttt{\{hyp\}}, are
substituted at call time. Two blocks are spliced into several prompts rather
than repeated: the paper block of Section~\ref{prompt:paper-block} and the
delta contract of Section~\ref{prompt:delta-spec}. Each is printed once, and
the prompts that carry it show \texttt{[[ THE PAPER BLOCK ]]} or
\texttt{[[ THE DELTA CONTRACT ]]} at the position where it is inserted.

@@BODY@@
"""

SECTION = r"""
\section{%s}
\label{prompt:%s}

%s

\begin{lstlisting}
%s
\end{lstlisting}
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path,
                    default=ROOT.parent / "figures" / "appendix_prompts.tex")
    a = ap.parse_args()

    N = load("nm", ROOT / "build" / "03_new_method.py")
    B = N.B
    paper, delta = N.PAPER_BLOCK, N.DELTA_SPEC
    # Plain markers, not \ref: listings is verbatim, so a cross-reference placed
    # inside one prints as the literal command. The references live in the prose
    # above each listing, where LaTeX will actually resolve them.
    cut = [(paper, "THE PAPER BLOCK"), (delta, "THE DELTA CONTRACT")]

    parts = [
        ("The paper block", "paper-block",
         "Prefixed to every prompt that needs the paper. Identical across them "
         "by construction: it is one string, so the paper's tokens are billed "
         "once per paper and read from cache thereafter.",
         clean(paper)),
        ("Phase 1: extract the target", "extract-target",
         "Recovers $b$ and $h^\\star$ before any citation is named, so that no "
         "reference can shape the hypothesis that is about to be frozen.",
         clean(N.EXTRACT_TARGET, cut)),
        ("Phase 1: verify the target", "verify-target",
         "Four conditions on the proposed target. The fourth is the "
         "disjointness of $b$ from $h^\\star$; a failure rewrites $b$ and never "
         "$h^\\star$, since $h^\\star$ is what the paper contributes.",
         clean(N.VERIFY_TARGET, cut)),
        ("The delta contract", "delta-spec",
         "Spliced verbatim into both Section~\\ref{prompt:find-inspirations} "
         "and Section~\\ref{prompt:rebuild}. $D_1$ and $D_{-j}$ are compared "
         "against one another, so any difference in how the two were instructed "
         "would surface as a difference between the decompositions.",
         clean(delta)),
        ("Phase 2: select inspirations and write the deltas", "find-inspirations",
         "Operates against a target it cannot revise. A rejected selection is "
         "re-searched; the background and hypothesis do not move.",
         clean(N.FIND_INSPIRATIONS, cut)),
        ("Phase 2: the four quality checks", "checks",
         "MOOSE-Star's checks, used unmodified and shared with the baseline arm "
         "so that both are judged by the same grader. They are predicates on the "
         "inspiration set $I$; the checker is shown the whole sequence $D$.",
         clean(B.CHECKS)),
        ("Phase 3: search for a replacement set", "substitute",
         "Chooses papers only. The excluded work stays visible in the reference "
         "list and the exclusion is enforced on the reply, which is stricter "
         "than trusting a shortened list and keeps the cached prefix identical.",
         clean(N.SUBSTITUTE, cut)),
        ("Phase 3: rebuild the decomposition", "rebuild",
         "Regenerates the entire ordered decomposition over the chosen set. "
         "Nothing is carried over: a kept inspiration's delta was written "
         "against a work that has just been removed.",
         clean(N.REBUILD, cut)),
    ]

    # A token, not %s: the preamble reminder in TEMPLATE is full of LaTeX
    # comments, and every one of those percent signs is a format specifier.
    body = "".join(SECTION % (t, lab, note, text) for t, lab, note, text in parts)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(TEMPLATE.replace("@@BODY@@", body), encoding="utf-8")

    non_ascii = sorted({c for _, _, _, t in parts for c in t if ord(c) > 127})
    print(f"-> {a.out}  ({len(parts)} prompts, "
          f"{sum(len(t) for _, _, _, t in parts):,} chars)")
    if non_ascii:
        print(f"   non-ASCII characters present: {''.join(non_ascii)}\n"
              f"   listings needs \\usepackage[utf8]{{inputenc}} with a T1 font, "
              f"or these will vanish silently.")


if __name__ == "__main__":
    main()
